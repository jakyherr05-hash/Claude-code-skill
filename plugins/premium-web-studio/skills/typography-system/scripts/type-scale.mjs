#!/usr/bin/env node
/**
 * Fluid modular type scale + spacing scale generator (CSS custom properties with clamp()).
 *
 * node type-scale.mjs [--min-vw 360] [--max-vw 1440] [--min-base 16] [--max-base 19]
 *                     [--min-ratio 1.2] [--max-ratio 1.333] [--steps -2,8] [--prefix step]
 *                     [--space-base 8] [--json]
 *
 * Why rem + vw in the preferred value: a pure-vw size ignores browser zoom/text-size (WCAG 1.4.4).
 * The rem intercept keeps text resizable; the min/max clamps keep extremes sane.
 * Line-height and tracking are emitted as SUGGESTIONS that tighten as size grows — tune by eye per font.
 */
const a = process.argv.slice(2);
const num = (k, d) => { const i = a.indexOf(`--${k}`); return i >= 0 ? Number(a[i + 1]) : d; };
const str = (k, d) => { const i = a.indexOf(`--${k}`); return i >= 0 ? a[i + 1] : d; };
const minVw = num('min-vw', 360), maxVw = num('max-vw', 1440);
const minBase = num('min-base', 16), maxBase = num('max-base', 19);
const minRatio = num('min-ratio', 1.2), maxRatio = num('max-ratio', 1.333);
const [lo, hi] = str('steps', '-2,8').split(',').map(Number);
const prefix = str('prefix', 'step');
const spaceBase = num('space-base', 8);
const r4 = (n) => Math.round(n * 10000) / 10000;

function fluid(minPx, maxPx) {
  const slope = (maxPx - minPx) / (maxVw - minVw);
  const intercept = minPx - slope * minVw;
  const [mn, mx] = [Math.min(minPx, maxPx), Math.max(minPx, maxPx)];
  return `clamp(${r4(mn / 16)}rem, ${r4(intercept / 16)}rem + ${r4(slope * 100)}vw, ${r4(mx / 16)}rem)`;
}
const lineHeight = (px) => (px >= 96 ? 0.92 : px >= 64 ? 0.98 : px >= 40 ? 1.06 : px >= 28 ? 1.15 : px >= 20 ? 1.35 : 1.55);
const tracking = (px) => (px >= 96 ? '-0.035em' : px >= 64 ? '-0.03em' : px >= 40 ? '-0.02em' : px >= 24 ? '-0.01em' : px >= 15 ? '0em' : '0.01em');

const rows = [];
for (let s = lo; s <= hi; s++) {
  const minPx = minBase * minRatio ** s, maxPx = maxBase * maxRatio ** s;
  rows.push({ token: `--${prefix}-${s}`, minPx: r4(minPx), maxPx: r4(maxPx), clamp: fluid(minPx, maxPx), lineHeight: lineHeight(maxPx), tracking: tracking(maxPx) });
}
// spacing: fluid pairs on a base unit (t-shirt sizes), each scaling ~1.25x from min to max viewport
const spaceSteps = { '3xs': 0.25, '2xs': 0.5, xs: 0.75, s: 1, m: 1.5, l: 2, xl: 3, '2xl': 4, '3xl': 6, '4xl': 8, '5xl': 12 };
const space = Object.entries(spaceSteps).map(([k, m]) => {
  const minPx = spaceBase * 2 * m * 0.8, maxPx = spaceBase * 2 * m;
  return { token: `--space-${k}`, minPx: r4(minPx), maxPx: r4(maxPx), clamp: fluid(minPx, maxPx) };
});

if (a.includes('--json')) { console.log(JSON.stringify({ minVw, maxVw, minBase, maxBase, minRatio, maxRatio, type: rows, space }, null, 2)); process.exit(0); }
console.log(`/* Fluid type scale: ${minBase}px@${minVw} → ${maxBase}px@${maxVw}, ratio ${minRatio} → ${maxRatio} (generated by type-scale.mjs) */`);
console.log(':root {');
for (const r of rows) console.log(`  ${r.token}: ${r.clamp}; /* ${r.minPx.toFixed(1)}→${r.maxPx.toFixed(1)}px · lh ${r.lineHeight} · tracking ${r.tracking} */`);
console.log('');
for (const s of space) console.log(`  ${s.token}: ${s.clamp}; /* ${s.minPx}→${s.maxPx}px */`);
console.log('}');
