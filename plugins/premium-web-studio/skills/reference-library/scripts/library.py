#!/usr/bin/env python3
"""
library.py — index and search the studio reference library (stdlib only).

  python3 library.py build                 rebuild index.json + INDEX.md from sites/*.md frontmatter
  python3 library.py search <terms...>     rank entries by terms across name/tags/category/body
         [--tag lenis] [--category studio] [--status inspected] [--min-confidence medium] [--limit 8]
  python3 library.py stale [--days 180]    entries older than N days (re-research candidates)

Each hit prints slug, status, confidence, date, tags and the matching lines, so you can open only the
entries that matter (token-cheap).
"""
import json, re, sys, datetime, pathlib, argparse

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITES = ROOT / "sites"
CONF = {"low": 0, "medium": 1, "high": 2}


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        return None
    meta = {}
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        k, v = line.split(":", 1)
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            v = [t.strip().strip("'\"").lower() for t in v[1:-1].split(",") if t.strip()]
        meta[k.strip()] = v
    meta["slug"] = meta.get("slug") or path.stem
    meta["file"] = f"sites/{path.name}"
    meta["_body"] = m.group(2)
    return meta


def entries():
    out = []
    for p in sorted(SITES.glob("*.md")):
        if p.name.startswith("_"):
            continue
        e = parse(p)
        if e:
            out.append(e)
    return out


def build():
    es = entries()
    idx = [{k: v for k, v in e.items() if not k.startswith("_")} for e in es]
    (ROOT / "index.json").write_text(json.dumps(idx, indent=2, ensure_ascii=False) + "\n")
    lines = ["# Reference library index", "", f"_{len(idx)} entries · generated by scripts/library.py build_", "",
             "| Site | Category | Status | Confidence | Researched | Tags |", "|---|---|---|---|---|---|"]
    for e in sorted(idx, key=lambda x: (x.get("category", ""), x.get("name", ""))):
        tags = ", ".join(e.get("tags", [])) if isinstance(e.get("tags"), list) else e.get("tags", "")
        lines.append(f"| [{e.get('name', e['slug'])}]({e['file']}) | {e.get('category', '')} | {e.get('status', '')} | {e.get('confidence', '')} | {e.get('researched', '')} | {tags} |")
    (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"indexed {len(idx)} entries → index.json, INDEX.md")


def search(a):
    terms = [t.lower() for t in a.terms]
    hits = []
    for e in entries():
        if a.tag and a.tag.lower() not in (e.get("tags") or []):
            continue
        if a.category and e.get("category") != a.category:
            continue
        if a.status and e.get("status") != a.status:
            continue
        if a.min_confidence and CONF.get(e.get("confidence", "low"), 0) < CONF[a.min_confidence]:
            continue
        body = e["_body"].lower()
        head = " ".join([str(e.get("name", "")), " ".join(e.get("tags") or []), str(e.get("category", ""))]).lower()
        score = sum(head.count(t) * 5 + body.count(t) for t in terms) if terms else 1
        if score:
            lines = [l.strip() for l in e["_body"].splitlines() if any(t in l.lower() for t in terms)][:3]
            hits.append((score, e, lines))
    hits.sort(key=lambda h: -h[0])
    for score, e, lines in hits[: a.limit]:
        print(f"[{score:>3}] {e['slug']:<18} {e.get('status', ''):<20} conf={e.get('confidence', '')} {e.get('researched', '')}  → {e['file']}")
        print(f"      tags: {', '.join(e.get('tags') or [])}")
        for l in lines:
            print(f"      · {l[:160]}")
    if not hits:
        print("no matches — consider researching new references (reference-study skill)")


def stale(days):
    today = datetime.date.today()
    for e in entries():
        try:
            d = datetime.date.fromisoformat(str(e.get("researched")))
        except ValueError:
            print(f"{e['slug']}: no valid date")
            continue
        if (today - d).days > days:
            print(f"{e['slug']}: researched {d} ({(today - d).days} days ago)")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    s = sub.add_parser("search")
    s.add_argument("terms", nargs="*")
    s.add_argument("--tag"); s.add_argument("--category"); s.add_argument("--status")
    s.add_argument("--min-confidence", choices=CONF)
    s.add_argument("--limit", type=int, default=8)
    st = sub.add_parser("stale")
    st.add_argument("--days", type=int, default=180)
    a = p.parse_args()
    {"build": lambda: build(), "search": lambda: search(a), "stale": lambda: stale(a.days)}[a.cmd]()
